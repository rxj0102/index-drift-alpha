"""Render the README results from results/metrics.json.

    python scripts/render_readme.py          rewrite the generated blocks
    python scripts/render_readme.py --check  exit 1 if the README is out of date
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MARK = "<!-- {name}:start (generated by scripts/render_readme.py, do not edit by hand) -->"
END = "<!-- {name}:end -->"
FLOW = ["addition_new", "addition_from_sp600", "deletion_to_sp600"]
LATE = FLOW + ["addition_from_sp500", "deletion_to_sp500", "deletion_other"]
EARLY = ["early_additions", "early_deletions"]


def cell(v) -> str:
    return "n/a" if not v else f"{v['mean']:+.2%} ({v['t']:+.1f})"


def headline(m: dict) -> str:
    g, meta = m["groups"], m["meta"]
    new, up, down = (g[k] for k in FLOW)
    sig = [(k, w) for k in FLOW for w in ("INTRADAY", "RUNUP", "AFTER") if g[k][w]["p_holm"] < 0.05]
    checks = {
        "the overnight gap is large and significant for all three flow groups":
            all(abs(g[k]["OVERNIGHT"]["t"]) > 5 for k in FLOW),
        "new additions and stocks moved down gap up, stocks moved up gap down":
            new["OVERNIGHT"]["mean"] > 0 and down["OVERNIGHT"]["mean"] > 0 and up["OVERNIGHT"]["mean"] < 0,
        "the only tradable cell that survives Holm is the first session of stocks moved up from the 600":
            sig == [("addition_from_sp600", "INTRADAY")],
        "nothing is significant from the first close to the fund trade, or after it":
            all(abs(g[k][w]["t"]) < 1.96 for k in FLOW for w in ("RUNUP", "AFTER")),
        "nothing on the effective day or after it": all(abs(g[k][w]["t"]) < 1.96 for k in FLOW for w in ("DAY0", "POST")),
        "stocks moved up already fall the session before": up["DAY_BEFORE"]["t"] < -1.96,
        "the surviving cell rests on 53 events over 30 dates":
            up["INTRADAY"]["n_events"] == 53 and up["INTRADAY"]["n_dates"] == 30,
        "most tradable means are under one percent":
            sum(abs(g[k][w]["mean"]) < 0.01 for k in FLOW for w in ("INTRADAY", "RUNUP", "AFTER")) >= 7,
        "stocks moved down from the S&P 500 barely gap":
            abs(g["addition_from_sp500"]["OVERNIGHT"]["mean"]) < 0.01 and abs(g["addition_from_sp500"]["OVERNIGHT"]["t"]) < 1.96,
        "stocks moved down move less than one percent the session before": abs(down["DAY_BEFORE"]["mean"]) < 0.01,
        "new additions do not move the session before": abs(new["DAY_BEFORE"]["t"]) < 1.96,
    }
    failed = [k for k, ok in checks.items() if not ok]
    if failed:
        raise SystemExit("README summary no longer matches the results; rewrite headline() in "
                         "scripts/render_readme.py. Failed: " + "; ".join(failed))
    return (
        f"**Answer, from {meta['n_with_prices']} events between {meta['event_start'][:4]} and "
        f"{meta['event_end'][:4]}: the price moves a lot, and it moves before you can trade.** Since 2020 a "
        f"stock newly added to the S&P 400 opens {new['OVERNIGHT']['mean']:.1%} higher than the market the "
        f"morning after the announcement (t = {new['OVERNIGHT']['t']:.1f}, up in "
        f"{new['OVERNIGHT']['share_positive']:.0%} of events). A stock demoted to the S&P 600 opens "
        f"{down['OVERNIGHT']['mean']:.1%} higher, and a stock promoted from the S&P 600 opens "
        f"{abs(up['OVERNIGHT']['mean']):.1%} lower, so the sign follows index fund demand, not good or bad news. "
        f"A stock moved down from the S&P 500 to the 400, where funds tracking the 500 sell what those tracking the "
        f"400 buy, barely moves ({g['addition_from_sp500']['OVERNIGHT']['mean']:+.1%}, t = "
        f"{g['addition_from_sp500']['OVERNIGHT']['t']:.1f}). "
        f"After that open there is nothing: from the first close to the day the funds trade, on the effective "
        f"day, and over the ten days after, none of the three has a significant return. Of {meta['n_tradable_tests']} "
        f"tradable tests one survives a multiple-testing correction, the first session of stocks promoted from "
        f"the S&P 600 ({up['INTRADAY']['mean']:+.1%}, corrected p = {up['INTRADAY']['p_holm']:.2f}), and that "
        f"group is the one whose announcement dates look least reliable."
    )


def results(m: dict) -> str:
    g, meta, lab = m["groups"], m["meta"], m["labels"]
    out = [f"{meta['n_events']} additions and non-merger deletions from {meta['event_start']} to {meta['event_end']} "
           f"({meta['n_mna_excluded']} merger deletions are left out). {meta['n_with_prices']} have prices "
           f"({meta['coverage']:.0%}; {meta['coverage_from_2020']:.0%} from 2020, {meta['coverage_before_2020']:.0%} "
           f"before). {meta['n_with_announcement']} also have a dated announcement; the median gap from the first "
           f"session after it to the effective date is {meta['median_gap_days']:.0f} trading days. Returns are "
           f"relative to MDY. Cells show the mean across event dates with its t-statistic.", "",
           "### Around the announcement, 2020 onward", "",
           "| Group | Events | Ten days before | Overnight gap | First session, open to close | Then to the fund trade "
           "| Effective day and ten after |", "|---|---|---|---|---|---|---|"]
    for k in LATE:
        v = g[k]
        out.append(f"| {lab[k]} | {v['n_with_announcement']} | {cell(v['BEFORE'])} | {cell(v['OVERNIGHT'])} | "
                   f"{cell(v['INTRADAY'])} | {cell(v['RUNUP'])} | {cell(v['AFTER'])} |")
    out += ["", "The overnight gap is the close before the announcement to the next open. Nobody who learns of the "
            "change from the announcement can trade at the earlier close, so only the last three columns are "
            "tradable.", "",
            "### The tradable windows, with a correction for nine tests", "",
            "| Group | Window | Mean | t | p | p, Holm | Median event | Share positive |", "|---|---|---|---|---|---|---|---|"]
    names = {"INTRADAY": "First session, open to close", "RUNUP": "First close to the fund trade",
             "AFTER": "Effective day and ten after"}
    for k in FLOW:
        for w, wn in names.items():
            v = g[k][w]
            out.append(f"| {lab[k]} | {wn} | {v['mean']:+.2%} | {v['t']:+.2f} | {v['p']:.3f} | {v['p_holm']:.2f} | "
                       f"{v['median_event']:+.2%} | {v['share_positive']:.0%} |")
    out += ["", "### A check on the dates", "",
            "Abnormal return in the last session before the one counted as the first reaction. It should be "
            "zero if the announcement dates are right and nothing leaked.", "",
            "| Group | Session before | t |", "|---|---|---|"]
    for k in FLOW:
        out.append(f"| {lab[k]} | {g[k]['DAY_BEFORE']['mean']:+.2%} | {g[k]['DAY_BEFORE']['t']:+.2f} |")
    out += ["", "### Around the effective date, all events with prices", "",
            "Day 0 is the effective date; index funds trade at the close of day -1.", "",
            "| Group | Events with prices | Days -20 to -6 | Days -5 to -1 | Day 0 | Days +1 to +10 |",
            "|---|---|---|---|---|---|"]
    for k in LATE + EARLY:
        v = g[k]
        out.append(f"| {lab[k]} | {v['n_with_prices']} of {v['n_events']} | {cell(v['PRE'])} | {cell(v['NEAR'])} | "
                   f"{cell(v['DAY0'])} | {cell(v['POST'])} |")
    out += ["", "Days -5 to -1 contain the announcement reaction for most events, which is why that column is large. "
            "Before 2020 origin and destination cannot be told apart, so opposite flows are pooled and the "
            "rows are weaker."]
    return "\n".join(out)


def fill(text: str, name: str, body: str) -> str:
    start, end = MARK.format(name=name), END.format(name=name)
    a, b = text.index(start) + len(start), text.index(end)
    return text[:a] + "\n" + body + "\n" + text[b:]


def main() -> None:
    m = json.loads((ROOT / "results" / "metrics.json").read_text())
    readme = ROOT / "README.md"
    text = readme.read_text()
    new = fill(fill(text, "headline", headline(m)), "results", results(m))
    if "--check" in sys.argv:
        if new != text:
            print("README is out of date; run python scripts/render_readme.py")
            sys.exit(1)
        print("README matches results/metrics.json")
        return
    readme.write_text(new)
    print("README rendered")


if __name__ == "__main__":
    main()
