"""S&P 400 addition and deletion event study, the testable form of the passive-flow hypothesis.

Events : Wikipedia, List of S&P 400 companies, changes table (effective dates), saved to
         data/reference/sp400_changes.csv so the study runs offline once fetched.
Prices : yfinance adjusted closes; benchmark MDY (SPDR S&P MidCap 400 ETF).
Windows: the repo's own config windows around the effective date (trading day 0):
         PRE [-20, -6], NEAR [-5, -1], DAY0 [0, 0], POST [+1, +10], plus FULL [-20, +10].
Abnormal return = stock return minus MDY return (market-adjusted model).
Inference: events sharing an effective date are averaged first, then a t-test runs across dates,
           so same-day events are not treated as independent.
Outputs: results/index_events.csv, results/event_study_car.csv, results/event_study_summary.json,
         and the README block between the event-study markers.

    python scripts/index_event_study.py           # fetch (if needed), compute, render README
    python scripts/index_event_study.py --check   # exit 1 if README is out of date with results/
"""
from __future__ import annotations

import json
import re
import sys
import urllib.request
from io import StringIO
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import config  # noqa: E402

RES = ROOT / "results"
REF = ROOT / "data" / "reference"
START_MARK = "<!-- event-study:start (generated by scripts/index_event_study.py, do not edit by hand) -->"
END_MARK = "<!-- event-study:end -->"
EVENT_START, EVENT_END = "2012-01-01", "2025-12-31"
CLASSIFIED_FROM = "2020-01-01"
ANN_WINDOWS = ["ANN_PRE", "ANN_DAY", "RUNUP", "AFTER"]  # the Wikipedia S&P 600 changes table starts 2019-12-17
WINDOWS = {
    "PRE": (config.WINDOW_PRE_START, config.WINDOW_PRE_END),
    "NEAR": (config.WINDOW_NEAR_START, config.WINDOW_NEAR_END),
    "DAY0": (0, 0),
    "POST": (config.WINDOW_POST_START, config.WINDOW_POST_END),
    "FULL": (config.WINDOW_PRE_START, config.WINDOW_POST_END),
}
UA = {"User-Agent": "index-drift-alpha research (github.com/rxj0102/index-drift-alpha)"}


def announcement_dates(html: str) -> list:
    """Announcement date per changes-table row, from the row's footnote.

    S&P Dow Jones Indices announcement URLs embed the date (indexnews/announcements/YYYYMMDD-...);
    otherwise the cite template's date parameter is used. Returns None where neither exists.
    """
    notes = {}
    for m in re.finditer(r'<li about="#(cite_note-[^"]+)" id="cite_note-[^"]+".*?</li>', html, re.S):
        body = m.group(0)
        u = re.search(r"indexnews/announcements/(\d{8})-", body)
        d = re.search(r'"date":\{"wt":"([^"]+)"', body)
        notes[m.group(1)] = pd.to_datetime(u.group(1), format="%Y%m%d") if u else (pd.to_datetime(d.group(1), errors="coerce") if d else pd.NaT)
    t = pd.read_html(StringIO(html), extract_links="body")[1]
    out = []
    for link in t.iloc[:, 5]:
        m = re.search(r"#(cite_note-\S+)", link[1] or "")
        out.append(notes.get(m.group(1), pd.NaT) if m else pd.NaT)
    return out


def load_changes() -> pd.DataFrame:
    path = REF / "sp400_changes.csv"
    if not path.exists() or "announcement_date" not in pd.read_csv(path, comment="#", nrows=1).columns:
        html = urllib.request.urlopen(urllib.request.Request(
            "https://en.wikipedia.org/wiki/List_of_S%26P_400_companies", headers=UA), timeout=60).read().decode()
        t = pd.read_html(StringIO(html))[1]
        t.columns = ["date", "added_ticker", "added_security", "removed_ticker", "removed_security", "reason"]
        t["reason"] = t["reason"].astype(str).str.replace(r"\[\d+\]", "", regex=True).str.strip()
        t["date"] = pd.to_datetime(t["date"], errors="coerce").dt.date
        t["announcement_date"] = [d.date() if pd.notna(d) else None for d in announcement_dates(html)]
        sp500 = pd.read_html(StringIO(urllib.request.urlopen(urllib.request.Request(
            "https://en.wikipedia.org/wiki/List_of_S%26P_500_companies", headers=UA), timeout=60).read().decode()))[0]
        header = ("# S&P 400 membership changes, from the changes table of the Wikipedia article List of S&P 400 companies.\n"
                  f"# Retrieved {pd.Timestamp.today().date()} by scripts/index_event_study.py. date is the effective date;\n"
                  "# announcement_date comes from the row's cited S&P Dow Jones Indices announcement (URL date or citation date).\n")
        path.write_text(header + t.to_csv(index=False))
        sp500[["Symbol", "Security", "Date added"]].to_csv(REF / "sp500_current_members.csv", index=False)
        s6 = pd.read_html(StringIO(urllib.request.urlopen(urllib.request.Request(
            "https://en.wikipedia.org/wiki/List_of_S%26P_600_companies", headers=UA), timeout=60).read().decode()))[1]
        s6.columns = ["date", "added_ticker", "added_security", "removed_ticker", "removed_security", "reason"]
        s6["date"] = pd.to_datetime(s6["date"], errors="coerce").dt.date
        s6.to_csv(REF / "sp600_changes.csv", index=False)
    return pd.read_csv(path, comment="#", parse_dates=["date", "announcement_date"])


def build_events(ch: pd.DataFrame) -> pd.DataFrame:
    sp500 = pd.read_csv(REF / "sp500_current_members.csv", parse_dates=["Date added"])
    up = dict(zip(sp500.Symbol, sp500["Date added"]))
    s6 = pd.read_csv(REF / "sp600_changes.csv", parse_dates=["date"]).dropna(subset=["date"])
    to600 = {(str(r.added_ticker).strip(), r.date) for r in s6.itertuples()}
    from600 = {(str(r.removed_ticker).strip(), r.date) for r in s6.itertuples()}

    def near(pairs, ticker, date):
        return any(t == ticker and abs((d - date).days) <= 10 for t, d in pairs)

    rows = []
    for _, r in ch.dropna(subset=["date"]).iterrows():
        if not (pd.Timestamp(EVENT_START) <= r.date <= pd.Timestamp(EVENT_END)):
            continue
        reason = str(r.reason).lower()
        mna = bool(re.search(r"acqui|merg|spun|spin|bought|takeover|purchase", reason))
        if isinstance(r.added_ticker, str) and r.added_ticker.strip():
            t = r.added_ticker.strip()
            sub = "addition_from_sp600" if near(from600, t, r.date) else "addition_new"
            rows.append({"date": r.date, "announcement_date": r.announcement_date, "ticker": t, "type": "addition", "subtype": sub, "reason": r.reason})
        if isinstance(r.removed_ticker, str) and r.removed_ticker.strip():
            t = r.removed_ticker.strip()
            if mna:
                sub = "deletion_mna"
            elif near(to600, t, r.date):
                sub = "deletion_to_sp600"
            elif t in up and abs((up[t] - r.date).days) <= 10:
                sub = "deletion_to_sp500"
            else:
                sub = "deletion_other"
            rows.append({"date": r.date, "announcement_date": r.announcement_date, "ticker": t, "type": "deletion", "subtype": sub, "reason": r.reason})
    return pd.DataFrame(rows)


def prices(tickers: list[str]) -> pd.DataFrame:
    import yfinance as yf

    cache = ROOT / "data" / "raw" / "event_study_prices.csv.gz"
    if cache.exists():
        return pd.read_csv(cache, index_col=0, parse_dates=True)
    frames = []
    yf_names = sorted({t.replace(".", "-") for t in tickers} | {"MDY"})
    for i in range(0, len(yf_names), 80):
        px = yf.download(yf_names[i:i + 80], start="2011-10-01", end="2026-02-01", auto_adjust=True,
                         progress=False, threads=True)["Close"]
        frames.append(px if isinstance(px, pd.DataFrame) else px.to_frame())
    out = pd.concat(frames, axis=1)
    out = out.loc[:, ~out.columns.duplicated()]
    cache.parent.mkdir(parents=True, exist_ok=True)
    out.to_csv(cache)
    return out


def compute() -> dict:
    ev = build_events(load_changes())
    px = prices(ev.ticker.unique().tolist())
    ret = px.pct_change()
    ar = ret.sub(ret["MDY"], axis=0)
    days = ar.index
    rows = []
    for _, e in ev.iterrows():
        col = e.ticker.replace(".", "-")
        pos = days.searchsorted(e.date)  # first trading day on or after the effective date
        out = {**e.to_dict(), "in_yfinance": col in ar.columns}
        if col in ar.columns and 20 <= pos < len(days) - 11:
            s = ar[col]
            for w, (a, b) in WINDOWS.items():
                seg = s.iloc[pos + a: pos + b + 1]
                out[f"CAR_{w}"] = float(seg.sum()) if seg.notna().all() and len(seg) == b - a + 1 else np.nan
            ann = e.announcement_date
            if pd.notna(ann) and 1 <= (e.date - ann).days <= 30:
                a0 = days.searchsorted(ann, side="right")  # announcements come after the close: first reaction day
                if 10 <= a0 < pos:
                    out["ann_to_eff_trading_days"] = int(pos - a0)
                    for w, (lo, hi) in {"ANN_PRE": (a0 - 10, a0 - 1), "ANN_DAY": (a0, a0),
                                        "RUNUP": (a0 + 1, pos - 1), "AFTER": (pos, pos + 10)}.items():
                        seg = s.iloc[lo: hi + 1]
                        out[f"CAR_{w}"] = float(seg.sum()) if hi < lo or (seg.notna().all() and len(seg) == hi - lo + 1) else np.nan
        rows.append(out)
    df = pd.DataFrame(rows)
    df.to_csv(RES / "event_study_car.csv", index=False)
    ev.to_csv(RES / "index_events.csv", index=False)

    def summarize(sub: pd.DataFrame) -> dict:
        res = {"n_events": int(len(sub)), "n_with_prices": int(sub["CAR_FULL"].notna().sum()),
               "n_with_announcement": int(sub["CAR_ANN_DAY"].notna().sum()) if "CAR_ANN_DAY" in sub.columns else 0}
        for w in list(WINDOWS) + ANN_WINDOWS:
            if f"CAR_{w}" not in sub.columns:
                continue
            by_date = sub.dropna(subset=[f"CAR_{w}"]).groupby("date")[f"CAR_{w}"].mean()
            if len(by_date) >= 5:
                t, p = stats.ttest_1samp(by_date, 0.0)
                ev_vals = sub[f"CAR_{w}"].dropna()
                res[w] = {"mean": float(by_date.mean()), "t": float(t), "p": float(p), "n_dates": int(len(by_date)),
                          "median_event": float(ev_vals.median()), "share_positive": float((ev_vals > 0).mean())}
        return res

    late = df.date >= CLASSIFIED_FROM
    nm = df.subtype != "deletion_mna"
    groups = {
        "addition_new": df[late & (df.subtype == "addition_new")],
        "addition_from_sp600": df[late & (df.subtype == "addition_from_sp600")],
        "deletion_to_sp600": df[late & (df.subtype == "deletion_to_sp600")],
        "deletion_to_sp500": df[late & (df.subtype == "deletion_to_sp500")],
        "deletion_other": df[late & (df.subtype == "deletion_other")],
        "early_additions": df[~late & (df.type == "addition")],
        "early_deletions": df[~late & (df.type == "deletion") & nm],
    }
    summary = {k: summarize(v) for k, v in groups.items()}
    summary["meta"] = {
        "event_window": f"{EVENT_START} to {EVENT_END}", "n_events": int(len(df)),
        "n_mna_deletions_excluded": int((df.subtype == "deletion_mna").sum()),
        "n_events_with_announcement": int(df["CAR_ANN_DAY"].notna().sum()),
        "median_ann_to_eff_trading_days": float(df["ann_to_eff_trading_days"].median()),
        "price_coverage_additions": float(df[df.type == "addition"].CAR_FULL.notna().mean()),
        "price_coverage_deletions": float(df[(df.type == "deletion") & (df.subtype != "deletion_mna")].CAR_FULL.notna().mean()),
    }
    RES.mkdir(exist_ok=True)
    (RES / "event_study_summary.json").write_text(json.dumps(summary, indent=2, default=str))
    return summary


def render(s: dict) -> str:
    m = s["meta"]
    lab = {"addition_new": "New additions (not from the S&P 600)", "addition_from_sp600": "Additions moved up from the S&P 600",
           "deletion_to_sp600": "Deletions moved down to the S&P 600", "deletion_to_sp500": "Deletions moved up to the S&P 500",
           "deletion_other": "Deletions, unclassified (not M&A)",
           "early_additions": "All additions, origin unknown", "early_deletions": "All non-M&A deletions, destination unknown"}
    o = [f"Market-adjusted cumulative abnormal returns (stock minus MDY) around S&P 400 effective dates, "
         f"events {m['event_window']}. Trading day 0 is the effective date; index funds trade at the close of day -1. "
         f"t-statistics average all events on the same date first, then test across dates. "
         f"{m['n_mna_deletions_excluded']} deletions driven by M&A are excluded. Cells show the mean CAR across event dates.", ""]
    o_head = ["| Group | Events with prices | PRE [-20,-6] | NEAR [-5,-1] | DAY0 [0] | POST [+1,+10] | FULL [-20,+10] | Median event NEAR |",
              "|---|---|---|---|---|---|---|---|"]
    def row(k):
        g = s[k]
        cells = [f"{g[w]['mean'] * 100:+.2f}% (t = {g[w]['t']:.2f})" if w in g else "n/a" for w in WINDOWS]
        return f"| {lab[k]} | {g['n_with_prices']} of {g['n_events']} | " + " | ".join(cells) + f" | {g['NEAR']['median_event'] * 100:+.2f}% |" if "NEAR" in g else ""
    o.append("**2020 to 2025, every event classified by origin or destination**")
    o.append("")
    o += o_head
    for k in ["addition_new", "addition_from_sp600", "deletion_to_sp600", "deletion_to_sp500", "deletion_other"]:
        o.append(row(k))
    o += ["", "**2012 to 2019, origin and destination not available (pooled)**", ""] + o_head
    for k in ["early_additions", "early_deletions"]:
        o.append(row(k))
    o += ["", "**Announcement decomposition, events with a dated S&P announcement (2012 to 2025)**", "",
          f"S&P announces after the close, so the reaction day A0 is the first trading day after the announcement date. "
          f"{m['n_events_with_announcement']} events have an announcement date and prices; the median gap from A0 to the effective date "
          f"is {m['median_ann_to_eff_trading_days']:.0f} trading days. RUNUP runs from the close of A0 to the close of the day before "
          "the effective date, when index funds trade; it is the part an investor could capture after seeing the announcement.", "",
          "| Group | Events | Before A0 [-10,-1] | Reaction A0 | RUNUP (A0, E-1] | AFTER [E, E+10] |", "|---|---|---|---|---|---|"]
    for k in ["addition_new", "addition_from_sp600", "deletion_to_sp600", "early_additions", "early_deletions"]:
        g = s[k]
        if "ANN_DAY" not in g:
            continue
        cells = [f"{g[w]['mean'] * 100:+.2f}% (t = {g[w]['t']:.2f})" if w in g else "n/a" for w in ANN_WINDOWS]
        o.append(f"| {lab[k]} | {g['n_with_announcement']} | " + " | ".join(cells) + " |")
    o += ["", f"Price coverage: {m['price_coverage_additions'] * 100:.0f}% of additions and "
          f"{m['price_coverage_deletions'] * 100:.0f}% of non-M&A deletions have yfinance prices for the full window. "
          "Firms that later delisted or changed ticker drop out, so results lean toward survivors. Moves to the S&P 600 are matched with the "
          "S&P 600 changes table; moves to the S&P 500 only with current S&P 500 members, so up-moves by firms that later left the "
          "S&P 500 sit in the unclassified group. "
          "In the first tables the NEAR window mixes the announcement reaction with the index-fund trade; the decomposition "
          "separates them for events with a dated announcement (2015 to 2018 citations mostly lack dates). Event list: `results/index_events.csv`; per-event CARs: `results/event_study_car.csv`."]
    return "\n".join(o)


def main() -> None:
    readme = ROOT / "README.md"
    text = readme.read_text()
    pre, rest = text.split(START_MARK, 1)
    _, post = rest.split(END_MARK, 1)
    if "--check" in sys.argv:
        s = json.loads((RES / "event_study_summary.json").read_text())
        if pre + START_MARK + "\n" + render(s) + "\n" + END_MARK + post != text:
            sys.exit("README event study is out of date. Run: python scripts/index_event_study.py")
        print("README event study matches results/")
        return
    s = compute()
    readme.write_text(pre + START_MARK + "\n" + render(s) + "\n" + END_MARK + post)
    print(render(s))


if __name__ == "__main__":
    main()
